const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {JSDOM}=require('jsdom');
const dom=new JSDOM('<!doctype html><body><div class="device"><iframe id="appFrame"></iframe></div><div id="area"></div></body>',{runScripts:'outside-only',url:'http://localhost/'});
const w=dom.window;
w.ResizeObserver=class{observe(){} disconnect(){}};
w.requestAnimationFrame=()=>0;
w.AppInterfaceStudio={androidCommand:async()=>({ok:true}),onAndroidVideo(){},onAndroidProgress(){}};
w.StudioWorkspace={getScreenProfile:()=>({width:384,height:824,kind:'smartphone'}),returnToLocal:()=>false};
w.StudioPhone={pushCurrentFrame(){}};
w.HTMLCanvasElement.prototype.getContext=function(){return {drawImage(){}}};
w.eval(fs.readFileSync(path.resolve(__dirname,'../../webapp/studio-native-simulation.js'),'utf8'));
const api=w.StudioNativeSimulation,area=w.document.getElementById('area');
assert(api,'native simulation API must load');
api.setEditorMirror(true);
const mirror=w.document.querySelector('.studio-native-editor-mirror');
assert(mirror,'editor mirror must exist');
assert.equal(mirror.hidden,true,'mirror must stay hidden before a real Android frame');
assert.equal(mirror.style.background,'transparent','mirror must never paint a black placeholder');
api.setExternalMode(true,area);
api.renderExternalFrame({},384,824);
assert.equal(mirror.hidden,false,'mirror becomes visible only after a real frame was drawn');
api.setEditorMirror(false);
assert.equal(mirror.hidden,true,'disabling exact rendering restores the editable view');
api.setSource(null,area,false);
api.setEditorMirror(true);
assert.equal(mirror.hidden,true,'changing source resets stale Android pixels and keeps editor visible until the next real frame');
console.log('Editor mirror: no black placeholder, real frame gating and source reset are enforced.');